def clean_release_repo(parent: Path) -> Path:
    root = parent / "repo"
    shutil.copytree(
        REPO,
        root,
        ignore=shutil.ignore_patterns(".git", "target", "output", "__pycache__"),
    )
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    subprocess.run(["git", "-C", str(root), "add", "."], check=True)
    subprocess.run(
        ["git", "-C", str(root), "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-qm", "fixture"],
        check=True,
    )
    return root


def fake_podman(path: Path, state: Path, log: Path) -> None:
    write(
        path,
        f"""
        #!/usr/bin/env python3
        import json, os, pathlib, sys
        args = sys.argv[1:]
        state_path = pathlib.Path({str(state)!r})
        log_path = pathlib.Path({str(log)!r})
        image_id = "sha256:" + "1" * 64
        if args == ["--version"]:
            print("podman version fixture")
            raise SystemExit(0)
        if args and args[0] == "build":
            log_path.write_text("\\n".join(args) + "\\n")
            values = {{}}
            for index, item in enumerate(args):
                if item == "--build-arg":
                    key, value = args[index + 1].split("=", 1)
                    values[key] = value
            pathlib.Path(args[args.index("--iidfile") + 1]).write_text(image_id + "\\n")
            state_path.write_text(json.dumps([{{
                "Id": image_id,
                "Digest": "sha256:" + "2" * 64,
                "RepoDigests": ["example@sha256:" + "2" * 64],
                "Config": {{"Labels": {{
                    "containers.bootc": "1",
                    "org.opencontainers.image.title": "SignalLayerIT CoreOS",
                    "org.opencontainers.image.version": values["PLANNED_OS_VERSION"],
                    "org.opencontainers.image.revision": values["SOURCE_REVISION"],
                    "org.signallayer.image.build-id": values["BUILD_ID"],
                }}}},
            }}]))
            raise SystemExit(0)
        if args[:2] == ["image", "inspect"]:
            if os.environ.get("FAKE_INSPECT_FAIL") == "1" and "--format" not in args:
                raise SystemExit(96)
            data = json.loads(state_path.read_text())
            if "--format" in args:
                print(os.environ.get("FAKE_TAG_ID", data[0]["Id"]))
            else:
                print(json.dumps(data))
            raise SystemExit(0)
        raise SystemExit(97)
        """,
    )
    path.chmod(0o755)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(content).lstrip())


def fixture(root: Path, os_version: str = "0.0.3.1", cargo_version: str = "0.0.3") -> None:
    write(root / "config/coreos-build-contract.json", "{}\n")
    write(
        root / "Cargo.toml",
        f"""
        [workspace]
        members = ["app"]
        resolver = "2"
        [workspace.package]
        version = "{cargo_version}"
        edition = "2021"
        """,
    )
    write(
        root / "app/Cargo.toml",
        """
        [package]
        name = "sl-test-app"
        version.workspace = true
        edition.workspace = true
        """,
    )
    write(root / "app/src/lib.rs", "pub fn value() -> u8 { 1 }\n")
    write(
        root / "Cargo.lock",
        f"""
        # This file is automatically @generated by Cargo.
        version = 4

        [[package]]
        name = "sl-test-app"
        version = "{cargo_version}"
        """,
    )
    write(
        root / "Containerfile",
        f"""
        ARG BUILD_ID=unknown
        FROM scratch
        LABEL org.opencontainers.image.version="{os_version}"
        LABEL org.signallayer.image.build-id="${{BUILD_ID}}"
        RUN printf '%s\\n' \\
            'VERSION="{os_version}"' \\
            > /usr/lib/signallayer/release
        """,
    )
    write(
        root / "image/build/build-qcow2.sh",
        f"""
        planned_os_version={os_version}
        source_ref=${{1:-localhost/signallayer-coreos:{os_version}}}
        run_dir=$(mktemp -d "$build_dir/output/coreos-{os_version}-x86_64.XXXXXXXX")
        [[ $(podman image inspect "$source_id" --format '{{{{index .Labels "org.opencontainers.image.version"}}}}') == "$planned_os_version" ]]
        podman tag "$source_id" localhost/signallayer-coreos:{os_version}
        image-builder build --bootc-ref localhost/signallayer-coreos:{os_version} \\
          --output-name signallayer-coreos-{os_version}-x86_64
        disk="$run_dir/signallayer-coreos-{os_version}-x86_64.qcow2"
        """,
    )
    write(
        root / "image/build/inspect-qcow2.sh",
        f"grep -q 'container-image-reference=.*localhost/signallayer-coreos:{os_version}' \"$origin\"\n",
    )
    write(
        root / "image/build/README.md",
        f"""
        # CoreOS {os_version} development disk
        --build-arg BUILD_ID="{os_version}-$(git rev-parse --short=12 HEAD)-local"
        `signallayer-coreos-{os_version}-x86_64.qcow2`
        """,
    )
    write(root / f"docs/releases/{os_version}.md", f"# SignalLayer CoreOS {os_version}\n")


class ReleasePreflightTests(unittest.TestCase):
    def run_preflight(self, root: Path, version: str, *extra: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [str(PREFLIGHT), version, "--root", str(root), *extra],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )

    def test_valid_independent_cargo_and_os_versions_pass(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root)
            result = self.run_preflight(root, "0.0.3.1")
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn("OS 0.0.3.1; Cargo 0.0.3", result.stdout)

    def test_invalid_os_version_fails(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root)
            result = self.run_preflight(root, "0.0.03.1")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("must be N.N.N or N.N.N.N", result.stderr)

    def test_planned_next_release_rejects_stale_consistent_tree(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
