#!/usr/bin/env python3
from __future__ import annotations

import subprocess
import tempfile
import textwrap
import unittest
from pathlib import Path


REPO = Path(__file__).resolve().parents[2]
PREFLIGHT = REPO / "tools/release-preflight"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(content).lstrip())


def fixture(root: Path, os_version: str = "0.0.3.1", cargo_version: str = "0.0.3") -> None:
    write(
        root / "Cargo.toml",
        f"""
        [workspace]
        members = ["app"]
        resolver = "2"
        [workspace.package]
        version = "{cargo_version}"
        edition = "2021"
        """,
    )
    write(
        root / "app/Cargo.toml",
        """
        [package]
        name = "sl-test-app"
        version.workspace = true
        edition.workspace = true
        """,
    )
    write(root / "app/src/lib.rs", "pub fn value() -> u8 { 1 }\n")
    write(
        root / "Cargo.lock",
        f"""
        # This file is automatically @generated by Cargo.
        version = 4

        [[package]]
        name = "sl-test-app"
        version = "{cargo_version}"
        """,
    )
    write(
        root / "Containerfile",
        f"""
        FROM scratch
        LABEL org.opencontainers.image.version="{os_version}"
        RUN printf '%s\\n' \\
            'VERSION="{os_version}"' \\
            > /usr/lib/signallayer/release
        """,
    )
    write(
        root / "image/build/build-qcow2.sh",
        f"""
        source_ref=${{1:-localhost/signallayer-coreos:{os_version}}}
        run_dir=$(mktemp -d "$build_dir/output/coreos-{os_version}-x86_64.XXXXXXXX")
        [[ $(podman image inspect "$source_id" --format '{{{{index .Labels "org.opencontainers.image.version"}}}}') == {os_version} ]]
        podman tag "$source_id" localhost/signallayer-coreos:{os_version}
        image-builder build --bootc-ref localhost/signallayer-coreos:{os_version} \\
          --output-name signallayer-coreos-{os_version}-x86_64
        disk="$run_dir/signallayer-coreos-{os_version}-x86_64.qcow2"
        """,
    )
    write(
        root / "image/build/inspect-qcow2.sh",
        f"grep -q 'container-image-reference=.*localhost/signallayer-coreos:{os_version}' \"$origin\"\n",
    )
    write(
        root / "image/build/README.md",
        f"""
        # CoreOS {os_version} development disk
        --build-arg BUILD_ID="{os_version}-$(git rev-parse --short=12 HEAD)-local"
        `signallayer-coreos-{os_version}-x86_64.qcow2`
        """,
    )
    write(root / f"docs/releases/{os_version}.md", f"# SignalLayer CoreOS {os_version}\n")


class ReleasePreflightTests(unittest.TestCase):
    def run_preflight(self, root: Path, version: str, *extra: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [str(PREFLIGHT), version, "--root", str(root), *extra],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )

    def test_valid_independent_cargo_and_os_versions_pass(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root)
            result = self.run_preflight(root, "0.0.3.1")
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn("OS 0.0.3.1; Cargo 0.0.3", result.stdout)

    def test_invalid_os_version_fails(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root)
            result = self.run_preflight(root, "0.0.03.1")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("must be N.N.N or N.N.N.N", result.stderr)

    def test_invalid_cargo_semver_fails(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root, cargo_version="0.0.3.1")
            result = self.run_preflight(root, "0.0.3.1")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("is not valid SemVer", result.stderr)

    def test_lock_mismatch_fails(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root)
            lock = root / "Cargo.lock"
            lock.write_text(lock.read_text().replace('version = "0.0.3"', 'version = "0.0.2"'))
            result = self.run_preflight(root, "0.0.3.1")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("Cargo.lock", result.stderr)

    def test_missing_identity_surface_fails(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root)
            (root / "docs/releases/0.0.3.1.md").unlink()
            result = self.run_preflight(root, "0.0.3.1")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("missing required identity surface", result.stderr)

    def test_mismatched_qcow2_identity_fails(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root)
            builder = root / "image/build/build-qcow2.sh"
            builder.write_text(builder.read_text().replace("--output-name signallayer-coreos-0.0.3.1", "--output-name signallayer-coreos-0.0.3"))
            result = self.run_preflight(root, "0.0.3.1")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("qcow2 artifact output name", result.stderr)

    def test_existing_tag_is_identity_safe_but_blocks_new_tag_gate(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            fixture(root)
            subprocess.run(["git", "init", "-q", str(root)], check=True)
            subprocess.run(["git", "-C", str(root), "add", "."], check=True)
            subprocess.run(
                ["git", "-C", str(root), "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-qm", "fixture"],
                check=True,
            )
            subprocess.run(["git", "-C", str(root), "tag", "v0.0.3.1"], check=True)
            identity = self.run_preflight(root, "0.0.3.1")
            self.assertEqual(identity.returncode, 0, identity.stderr)
            self.assertIn("protected historical tag v0.0.3.1 exists", identity.stdout)
            authorization = self.run_preflight(root, "0.0.3.1", "--require-new-tag")
            self.assertNotEqual(authorization.returncode, 0)
            self.assertIn("refusing new-tag authorization", authorization.stderr)

    def test_build_entrypoints_run_preflight_before_expensive_work(self) -> None:
        containerfile = (REPO / "Containerfile").read_text()
        preflight = "RUN python3 tools/release-preflight 0.0.3.1"
        first = containerfile.index(preflight)
        install_tools = containerfile.index("RUN dnf -y install", first)
        second = containerfile.index(preflight, first + len(preflight))
        compile_workspace = containerfile.index("RUN cargo fmt", second)
        self.assertLess(first, install_tools)
        self.assertLess(install_tools, second)
        self.assertLess(second, compile_workspace)

        builder = (REPO / "image/build/build-qcow2.sh").read_text()
        gate = builder.index('python3 "$repo_root/tools/release-preflight" 0.0.3.1')
        output = builder.index('mkdir -p "$build_dir/output"')
        podman = builder.index("podman image inspect")
        self.assertLess(gate, output)
        self.assertLess(gate, podman)


if __name__ == "__main__":
    unittest.main()
